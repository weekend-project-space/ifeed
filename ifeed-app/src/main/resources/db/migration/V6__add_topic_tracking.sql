CREATE TABLE topic_tracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_uid UUID NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    keyword VARCHAR(240) NOT NULL,
    include_keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
    blocked_keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
    categories JSONB NOT NULL DEFAULT '[]'::jsonb,
    relevance_prompt TEXT NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_run_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_topic_tracks_user_updated ON topic_tracks(user_id, updated_at DESC);

CREATE TABLE topic_track_sources (
    topic_track_id BIGINT NOT NULL REFERENCES topic_tracks(id) ON DELETE CASCADE,
    feed_id INTEGER NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
    PRIMARY KEY (topic_track_id, feed_id)
);

CREATE TABLE topic_track_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_track_id BIGINT NOT NULL REFERENCES topic_tracks(id) ON DELETE CASCADE,
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    category VARCHAR(32) NOT NULL,
    matched_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_topic_track_matches_track_article UNIQUE (topic_track_id, article_id)
);

CREATE INDEX idx_topic_track_matches_track_matched ON topic_track_matches(topic_track_id, matched_at DESC);

CREATE TABLE topic_track_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_uid UUID NOT NULL UNIQUE,
    topic_track_id BIGINT NOT NULL REFERENCES topic_tracks(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    summary TEXT NOT NULL,
    article_count INTEGER NOT NULL,
    article_previews JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_topic_track_summaries_user_created ON topic_track_summaries(user_id, created_at DESC);
